//! The C constants, the C++ name accessors and the C++ test cases of every
//! field the C ABI carries as an integer code, rendered from
//! `thetadatadx::coded_fields()` and, for the event kind, from the streaming
//! event table:
//!
//! - `thetadatadx-cpp/include/codes.h.inc`: a `THETADATADX_<FIELD>_<NAME>`
//!   constant for every code, `#include`'d from `thetadatadx.h`. The event
//!   kind has its constants already, as the enumerators of
//!   `ThetaDataDxStreamEventKind`;
//! - `thetadatadx-cpp/include/code_names.hpp.inc`: `thetadatadx::<field>_name`,
//!   the name Python and TypeScript give each code, `#include`'d from
//!   `thetadatadx.hpp`;
//! - `thetadatadx-cpp/tests/code_names.inc`: one `{field, code, name}` row per
//!   code, the cases the C++ test holds those accessors to.

use std::fmt::Write as _;
use std::path::Path;

use heck::{ToShoutySnakeCase, ToSnakeCase};

use crate::fpss_events::EVENTS;

/// One coded field, with the names it renders under.
struct Field {
    field: String,
    c_prefix: String,
    doc: String,
    codes: Vec<(i32, String)>,
    unknown: String,
}

impl Field {
    /// The C constant of a code's name.
    fn constant(&self, name: &str) -> String {
        format!(
            "THETADATADX_{}_{}",
            self.c_prefix,
            name.to_shouty_snake_case()
        )
    }
}

/// The core table's fields, which need C constants.
fn table_fields() -> Vec<Field> {
    thetadatadx::coded_fields()
        .into_iter()
        .map(|f| Field {
            field: f.field.to_owned(),
            c_prefix: f.c_prefix,
            doc: f.doc.to_owned(),
            codes: f
                .codes
                .into_iter()
                .map(|(code, name)| (code, name.to_owned()))
                .collect(),
            unknown: f.unknown.to_owned(),
        })
        .collect()
}

/// The event kind: `ThetaDataDxStreamEventKind`, whose value is the event's
/// position in the table and whose name is its `kind` tag.
fn kind_field() -> Field {
    Field {
        field: "kind".to_owned(),
        c_prefix: "STREAM".to_owned(),
        doc: "Kind of a streaming event, carried by `ThetaDataDxStreamEvent.kind`.".to_owned(),
        codes: (0..)
            .zip(EVENTS)
            .map(|(code, event)| (code, event.name.to_snake_case()))
            .collect(),
        unknown: "UNKNOWN".to_owned(),
    }
}

/// Every field, checked to render: plain names, and constants and codes that
/// are each unique within their field.
fn fields() -> (Vec<Field>, Field) {
    let (table, kind) = (table_fields(), kind_field());
    for field in table.iter().chain([&kind]) {
        let mut seen = std::collections::HashSet::new();
        for (code, name) in &field.codes {
            assert!(
                name.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_'),
                "{} code {code} has a name '{name}' that is not a plain identifier",
                field.field
            );
            assert!(
                seen.insert(*code),
                "{} defines code {code} twice",
                field.field
            );
        }
        let constants: std::collections::HashSet<_> = field
            .codes
            .iter()
            .map(|(_, name)| field.constant(name))
            .collect();
        assert_eq!(
            constants.len(),
            field.codes.len(),
            "two names of {} share a C constant",
            field.field
        );
    }
    (table, kind)
}

fn render_c(table: &[Field]) -> String {
    let mut out = String::from(
        "/* @generated DO NOT EDIT: regenerated by generate_sdk_surfaces from the coded fields table */\n",
    );
    for field in table {
        writeln!(out, "\n/* {} */", field.doc).unwrap();
        for (code, name) in &field.codes {
            // Parenthesised when negative, as the header's other negative codes are.
            let value = if *code < 0 {
                format!("({code})")
            } else {
                code.to_string()
            };
            writeln!(out, "#define {} {value}", field.constant(name)).unwrap();
        }
    }
    out
}

fn render_cpp(table: &[Field], kind: &Field) -> String {
    let mut out = String::from(
        "/* @generated DO NOT EDIT: regenerated by generate_sdk_surfaces from the coded fields table\n \
         * and the streaming event table */\n",
    );
    for field in table.iter().chain([kind]) {
        writeln!(out, "\n/// {}", field.doc).unwrap();
        writeln!(
            out,
            "///\n/// Returns the name Python and TypeScript give a `THETADATADX_{}_*` code, or `\"{}\"` for any other code.",
            field.c_prefix, field.unknown
        )
        .unwrap();
        writeln!(
            out,
            "inline std::string_view {}_name(int32_t code) noexcept {{\n    switch (code) {{",
            field.field
        )
        .unwrap();
        for (_, name) in &field.codes {
            writeln!(
                out,
                "        case {}:\n            return \"{name}\";",
                field.constant(name)
            )
            .unwrap();
        }
        writeln!(
            out,
            "        default:\n            return \"{}\";\n    }}\n}}",
            field.unknown
        )
        .unwrap();
    }
    out
}

fn render_cases(table: &[Field], kind: &Field) -> String {
    let mut out = String::from(
        "// @generated DO NOT EDIT: regenerated by generate_sdk_surfaces from the coded fields table\n\
         // and the streaming event table. One row per code: the field, the code and its name.\n",
    );
    for field in table.iter().chain([kind]) {
        for (code, name) in &field.codes {
            writeln!(out, "{{\"{}\", {code}, \"{name}\"}},", field.field).unwrap();
        }
    }
    out
}

fn render_files() -> [(&'static str, String); 3] {
    let (table, kind) = fields();
    [
        ("thetadatadx-cpp/include/codes.h.inc", render_c(&table)),
        (
            "thetadatadx-cpp/include/code_names.hpp.inc",
            render_cpp(&table, &kind),
        ),
        (
            "thetadatadx-cpp/tests/code_names.inc",
            render_cases(&table, &kind),
        ),
    ]
}

/// Renders the coded-field headers and test cases and writes each to its path under the repository root.
pub fn write_sdk_generated_files(repo_root: &Path) -> Result<(), Box<dyn std::error::Error>> {
    for (path, contents) in render_files() {
        std::fs::write(repo_root.join(path), contents)?;
    }
    Ok(())
}

/// Verifies that the checked-in coded-field headers and test cases match freshly rendered output, returning an error on drift.
pub fn check_sdk_generated_files(repo_root: &Path) -> Result<(), Box<dyn std::error::Error>> {
    for (path, contents) in render_files() {
        let current = std::fs::read_to_string(repo_root.join(path)).unwrap_or_default();
        if current.replace("\r\n", "\n") != contents {
            return Err(format!(
                "generated file out of date: {path} (run: cargo run -p xtask --bin generate_sdk_surfaces)"
            )
            .into());
        }
    }
    Ok(())
}
