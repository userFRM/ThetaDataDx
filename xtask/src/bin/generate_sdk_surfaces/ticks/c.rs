//! C header emitter for the tick structs and their entry points.

use std::fmt::Write as _;

use heck::ToSnakeCase;

use super::idents::c_field_ident;
use super::table::ticks_by_name;

/// The C type of a table column type and its size in bytes.
fn c_type(ty: &str) -> (&'static str, usize) {
    match ty {
        "i32" | "eod_num" | "eod_date" | "calendar_status" => ("int32_t", 4),
        "i64" | "eod_num64" => ("int64_t", 8),
        "f64" | "price" | "eod_price" => ("double", 8),
        other => panic!("no C type for tick column type '{other}'"),
    }
}

/// Renders `thetadatadx-cpp/include/ticks.h.inc`: every tick struct with a C
/// layout, its array type, its free function and its Arrow IPC entry points.
/// The struct members follow the Rust row's declaration order, so the C
/// compiler lays them out as `#[repr(C)]` does; the C++ layout asserts check
/// it did.
pub(super) fn render_c_ticks() -> String {
    let ticks: Vec<_> = ticks_by_name()
        .into_iter()
        .filter(|tick| tick.layout.is_some())
        .collect();
    let mut out = String::new();
    out.push_str("/* @generated DO NOT EDIT: regenerated by generate_sdk_surfaces from the tick table */\n\n");
    for tick in &ticks {
        let layout = tick
            .layout
            .as_ref()
            .expect("filtered to rows with a C layout");
        // The first paragraph: the later ones describe the decode.
        let paragraph = tick.more.iter().take_while(|line| !line.is_empty());
        writeln!(
            out,
            "/* {} */",
            std::iter::once(&tick.summary)
                .chain(paragraph)
                .copied()
                .collect::<Vec<_>>()
                .join("\n * ")
        )
        .unwrap();
        out.push_str("THETADATADX_ALIGN64_BEGIN typedef struct {\n");
        let mut end = 0;
        for column in tick.columns {
            let field = c_field_ident(column.field);
            let (ty, size) = c_type(column.ty);
            if column.ty == "calendar_status" {
                out.push_str(
                    "    /* One of the THETADATADX_CALENDAR_STATUS_* codes; string form via\n",
                );
                out.push_str("     * thetadatadx_calendar_status_name(). */\n");
            }
            writeln!(out, "    {ty} {field};").unwrap();
            end = offset(layout.offsets, column.field) + size;
            let has = format!("has_{}", column.field);
            if layout.offsets.iter().any(|&(name, _)| name == has) {
                writeln!(out, "    bool {has};").unwrap();
                end = offset(layout.offsets, &has) + 1;
            }
        }
        if tick.contract_id {
            out.push_str("    int32_t expiration;\n");
            out.push_str("    double strike;\n");
            out.push_str(
                "    /* Unicode scalar value of the right character: 'C' (67) for a call,\n",
            );
            out.push_str("     * 'P' (80) for a put, 0 when contract identity is absent\n");
            out.push_str("     * (single-contract queries). Cast to char for display. */\n");
            out.push_str("    uint32_t right;\n");
            end = offset(layout.offsets, "right") + 4;
        }
        if layout.size > end {
            writeln!(out, "    uint8_t _tail_padding[{}];", layout.size - end).unwrap();
        }
        writeln!(
            out,
            "}} ThetaDataDx{} THETADATADX_ALIGN64_END;\n",
            tick.name
        )
        .unwrap();
    }

    out.push_str(
        "/* Owned tick-array views: { const T* data; size_t len; }. Returned by the\n\
         \x20* matching thetadatadx_* data call; each MUST be freed with its\n\
         \x20* thetadatadx_*_array_free (below). An empty result is data=NULL, len=0. */\n",
    );
    for tick in &ticks {
        let name = tick.name;
        writeln!(out, "typedef struct {{ const ThetaDataDx{name}* data; size_t len; }} ThetaDataDx{name}Array;").unwrap();
    }

    out.push_str(
        "\n/** Each frees the array returned by its matching thetadatadx_* data call and\n\
         \x20*  releases the backing allocation.\n\
         \x20*  @param arr The array returned by the matching data call; a NULL/empty\n\
         \x20*             (data=NULL, len=0) array is a no-op.\n\
         \x20*  @note Call exactly once per returned array. */\n",
    );
    for tick in &ticks {
        let (name, snake) = (tick.name, tick.name.to_snake_case());
        writeln!(
            out,
            "void thetadatadx_{snake}_array_free(ThetaDataDx{name}Array arr);"
        )
        .unwrap();
    }

    out.push_str(
        "\n/** Serialise a span of history tick rows as an Arrow IPC stream, the same\n\
         \x20*  columnar exit Python exposes via <TickName>List.to_arrow(). The element\n\
         \x20*  type is the layout-pinned tick struct the matching history endpoint\n\
         \x20*  returns.\n\
         \x20*  @param rows Pointer to the tick rows to serialise; may be NULL only when\n\
         \x20*              len is 0 (a valid zero-row stream).\n\
         \x20*  @param len Number of rows referenced by rows.\n\
         \x20*  @return An Arrow IPC byte buffer on success that the caller MUST free with\n\
         \x20*          thetadatadx_arrow_bytes_free, or (data=NULL, len=0) on error with\n\
         \x20*          thetadatadx_last_error() set. */\n",
    );
    for tick in &ticks {
        let (name, snake) = (tick.name, format!("{}s", tick.name).to_snake_case());
        writeln!(
            out,
            "ThetaDataDxArrowBytes thetadatadx_{snake}_to_arrow_ipc(const ThetaDataDx{name}* rows, size_t len);"
        )
        .unwrap();
    }

    out.push_str(
        "\n/* Build the wire-column presence set for a response from its header names\n\
         \x20* (the DataTable headers), via the same decode logic the buffered .await path\n\
         \x20* uses. headers may be NULL only when len is 0. The returned carrier MUST be\n\
         \x20* freed with thetadatadx_column_presence_free. */\n",
    );
    for tick in &ticks {
        let snake = format!("{}s", tick.name).to_snake_case();
        writeln!(
            out,
            "ThetaDataDxColumnPresence thetadatadx_{snake}_present_columns(const char* const* headers, size_t len);"
        )
        .unwrap();
    }

    out.push_str(
        "\n/* Serialise a span of history tick rows as a PROJECTED Arrow IPC stream:\n\
         \x20* only the columns presence names (from the matching _present_columns), the\n\
         \x20* terminal-exact columnar exit Python's <TickName>List.to_arrow() gives on a\n\
         \x20* decode result. rows may be NULL only when len is 0. The presence carrier is\n\
         \x20* borrowed (still owned by the caller). Returns an Arrow IPC byte buffer the\n\
         \x20* caller MUST free with thetadatadx_arrow_bytes_free, or (data=NULL, len=0) on\n\
         \x20* error with thetadatadx_last_error() set. */\n",
    );
    for tick in &ticks {
        let (name, snake) = (tick.name, format!("{}s", tick.name).to_snake_case());
        writeln!(
            out,
            "ThetaDataDxArrowBytes thetadatadx_{snake}_to_arrow_ipc_projected(const ThetaDataDx{name}* rows, size_t len, ThetaDataDxColumnPresence presence, const char* symbol);"
        )
        .unwrap();
    }
    out
}

/// The offset of a field of a row's layout.
fn offset(offsets: &[(&str, usize)], field: &str) -> usize {
    offsets
        .iter()
        .find(|&&(name, _)| name == field)
        .unwrap_or_else(|| panic!("no offset recorded for field '{field}'"))
        .1
}
