//! The code tables the docs site publishes as a page and a CSV download each:
//! exchanges, trade conditions and quote conditions, rendered from the
//! lookup tables the SDK answers from.

use std::fmt::Write as _;

use thetadatadx::utils::conditions::{QUOTE_CONDITIONS, TRADE_CONDITIONS};
use thetadatadx::utils::exchange::EXCHANGES;

use super::DocFile;

/// A table cell: text, or a flag the page marks with a tick and the CSV
/// writes as `true` or `false`.
enum Cell {
    Text(String),
    Flag(bool),
}

/// The page `docs/articles/<slug>.md`, with the rows in place of `{rows}`,
/// and its download `docs/public/csv/<slug>.csv`.
fn render(slug: &str, page: &str, csv_header: &str, rows: Vec<Vec<Cell>>) -> [DocFile; 2] {
    let mut table = String::new();
    let mut csv = format!("{csv_header}\n");
    for row in rows {
        let mut fields = Vec::new();
        for cell in row {
            match cell {
                Cell::Text(text) => {
                    let _ = write!(table, "| {} ", text.replace('|', "\\|"));
                    fields.push(if text.contains([',', '"']) {
                        format!("\"{}\"", text.replace('"', "\"\""))
                    } else {
                        text
                    });
                }
                Cell::Flag(flag) => {
                    table.push_str(if flag { "| ✓ " } else { "|  " });
                    fields.push(flag.to_string());
                }
            }
        }
        table.push_str("|\n");
        let _ = writeln!(csv, "{}", fields.join(","));
    }
    [
        DocFile {
            relative_path: format!("docs-site/docs/articles/{slug}.md"),
            contents: page.replace("{rows}", &table),
        },
        DocFile {
            relative_path: format!("docs-site/docs/public/csv/{slug}.csv"),
            contents: csv,
        },
    ]
}

const GENERATED: &str = "<!-- @generated by `generate_sdk_surfaces` from the SDK's code tables. Do not edit by hand. -->";

/// The three code pages and their CSV downloads.
pub(super) fn render_code_pages() -> Vec<DocFile> {
    let text = |value: &str| Cell::Text(value.to_string());
    let exchanges = render(
        "exchanges",
        &format!(
            "---\ntitle: Exchanges\ndescription: Exchange code mapping for the exchange fields on trade and quote rows.\n---\n\n\
             {GENERATED}\n\n\
             # Exchanges\n\n\
             The integer `exchange`, `bid_exchange`, and `ask_exchange` response fields use these codes, as published by ThetaData. \
             The names and symbols are the ones the SDK's exchange lookups return.\n\n\
             [Download as CSV](/csv/exchanges.csv)\n\n\
             | Code | Name | Symbol |\n|---:|---|---|\n{{rows}}\n\
             Source: ThetaData's [Exchanges article](https://docs.thetadata.us/Articles/Errors-Exchanges-Conditions/Exchanges.html).\n"
        ),
        "code,name,symbol",
        EXCHANGES
            .iter()
            .map(|e| vec![text(&e.code.to_string()), text(e.name), text(e.symbol)])
            .collect(),
    );
    let trade = render(
        "trade-conditions",
        &format!(
            "---\ntitle: Trade Conditions\ndescription: The full ThetaData trade-condition code table for the condition fields on trade rows.\n---\n\n\
             {GENERATED}\n\n\
             # Trade Conditions\n\n\
             Trade rows carry a `condition` code plus `ext_condition1`–`4`. Below is ThetaData's complete published trade-condition set, \
             as the SDK's condition lookups return it: every code, its per-flag behavior (whether it cancels, is a late/open report, \
             updates volume / high / low / last), and its description. \
             Quote-row condition fields are on the [Quote Conditions](/articles/quote-conditions) page.\n\n\
             [Download as CSV](/csv/trade-conditions.csv)\n\n\
             Legend: ✓ = yes, blank = no. Source: ThetaData's \
             [Trade Conditions article](https://docs.thetadata.us/Articles/Errors-Exchanges-Conditions/Trade-Conditions.html).\n\n\
             | Code | Name | Cancel | Late Report | Auto Executed | Open Report | Volume | High | Low | Last | Description |\n\
             |---:|---|:-:|:-:|:-:|:-:|:-:|:-:|:-:|:-:|---|\n{{rows}}"
        ),
        "Code,Name,Cancel,LateReport,AutoExecuted,OpenReport,Volume,High,Low,Last,Description",
        TRADE_CONDITIONS
            .iter()
            .map(|c| {
                vec![
                    text(&c.code.to_string()),
                    text(c.name),
                    Cell::Flag(c.cancel),
                    Cell::Flag(c.late_report),
                    Cell::Flag(c.auto_executed),
                    Cell::Flag(c.open_report),
                    Cell::Flag(c.volume),
                    Cell::Flag(c.high),
                    Cell::Flag(c.low),
                    Cell::Flag(c.last),
                    text(c.description),
                ]
            })
            .collect(),
    );
    let quote = render(
        "quote-conditions",
        &format!(
            "---\ntitle: Quote Conditions\ndescription: The full ThetaData quote-condition code table for the condition fields on quote rows.\n---\n\n\
             {GENERATED}\n\n\
             # Quote Conditions\n\n\
             Quote rows carry `bid_condition` / `ask_condition` codes. Below is ThetaData's complete published quote-condition set, \
             as the SDK's condition lookups return it: every code, whether the quote is firm, and whether it denotes a halt. \
             Trade-row condition fields are on the [Trade Conditions](/articles/trade-conditions) page.\n\n\
             [Download as CSV](/csv/quote-conditions.csv)\n\n\
             Legend: ✓ = yes, blank = no. Source: ThetaData's \
             [Quote Conditions article](https://docs.thetadata.us/Articles/Errors-Exchanges-Conditions/Quote-Conditions.html).\n\n\
             | Code | Name | Firm | Halted |\n|---:|---|:-:|:-:|\n{{rows}}"
        ),
        "Code,Name,Firm,Halted",
        QUOTE_CONDITIONS
            .iter()
            .map(|c| {
                vec![
                    text(&c.code.to_string()),
                    text(c.name),
                    Cell::Flag(c.firm),
                    Cell::Flag(c.halted),
                ]
            })
            .collect(),
    );
    [exchanges, trade, quote].into_iter().flatten().collect()
}
