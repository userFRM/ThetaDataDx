#!/usr/bin/env python3
"""Rebuild the napi bindings and fail if the committed output moved.

`thetadatadx-ts/index.d.ts` and `index.js` are generated by the napi
toolchain and committed, so anything that changes the Rust surface — or the
generator itself — changes them. CI rebuilds and diffs; the rest of the gate
suite does not, which is why declaration drift has repeatedly reached CI
green-on-local. This is that check, runnable before a push.

It is deliberately not part of `ci.py all`: it compiles the crate, which is
minutes, and a gate people skip is worse than one they run on purpose. Run
it whenever a change touches the TypeScript surface or bumps the napi
toolchain.
"""

from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

TS_DIR = Path(__file__).resolve().parents[2] / "thetadatadx-ts"
GENERATED = ("index.d.ts", "index.js")


def main() -> int:
    if shutil.which("npm") is None:
        # Not a pass: say why, so a clean exit is never mistaken for a check
        # that ran.
        print("napi drift: npm is not installed; cannot verify", file=sys.stderr)
        return 2

    # Install from the lockfile first. Without it the build uses whatever
    # node_modules happens to be on disk, which after working on another
    # branch is a different napi toolchain — and a different toolchain emits
    # different output, so the gate reports drift that is not in the tree.
    install = subprocess.run(
        ["npm", "ci"], cwd=TS_DIR, capture_output=True, text=True
    )
    if install.returncode != 0:
        print(install.stderr[-4000:], file=sys.stderr)
        print("napi drift: npm ci failed, so drift could not be checked", file=sys.stderr)
        return install.returncode

    build = subprocess.run(
        ["npm", "run", "build"], cwd=TS_DIR, capture_output=True, text=True
    )
    if build.returncode != 0:
        print(build.stdout[-4000:], file=sys.stderr)
        print(build.stderr[-4000:], file=sys.stderr)
        print("napi drift: the build failed, so drift could not be checked", file=sys.stderr)
        return build.returncode

    diff = subprocess.run(
        ["git", "diff", "--exit-code", "--", *GENERATED],
        cwd=TS_DIR,
        capture_output=True,
        text=True,
    )
    if diff.returncode != 0:
        print(diff.stdout, file=sys.stderr)
        print(
            "napi drift: the committed napi output does not match a fresh build.\n"
            "Commit the regenerated " + " and ".join(GENERATED) + ".",
            file=sys.stderr,
        )
        return 1

    print("napi drift: committed output matches a fresh build")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
