//! The live parameter-mode matrix, one cell per (endpoint, mode), rendered
//! for the two validators that run it against a real account.
//!
//! The Python validator (`scripts/ci/check_python.py`) reads the cells as
//! data and calls each endpoint by name. C++ cannot call a method by name, so
//! its validator (`thetadatadx-cpp/examples/validate.cpp`) includes the
//! cells as rendered calls. Both come from [`test_modes_for`], so the two
//! languages run the same cells and `check_agreement.py` can compare them.

use std::fmt::Write as _;

use serde_json::{Map, Value, json};

use super::super::modes::{TestMode, is_chain_wide_mode, test_modes_for};
use super::super::sdk_helpers::{
    cpp_arg_literal, cpp_builder_setter, json_arg, json_builder_value, method_params,
};
use super::super::table::GeneratedEndpoint;

const GENERATED: &str = "DO NOT EDIT: regenerated by generate_sdk_surfaces from the endpoint table";

/// Every cell of the matrix, in endpoint-table order.
fn cells(endpoints: &[GeneratedEndpoint]) -> impl Iterator<Item = (&GeneratedEndpoint, TestMode)> {
    endpoints.iter().flat_map(|endpoint| {
        test_modes_for(endpoint)
            .into_iter()
            .map(move |mode| (endpoint, mode))
    })
}

/// The per-call deadline the SDK enforces on a cell. A chain-wide cell gets
/// three minutes because the vendor takes close to one even for the bounded
/// request.
fn timeout_ms(mode: &TestMode) -> u32 {
    if is_chain_wide_mode(&mode.name) {
        180_000
    } else {
        60_000
    }
}

/// The cells as JSON, one per line: positional `args` and keyword `options`
/// typed as the Python method takes them.
pub(super) fn render_cells_json(endpoints: &[GeneratedEndpoint]) -> String {
    let rows: Vec<String> = cells(endpoints)
        .map(|(endpoint, mode)| {
            let args: Vec<Value> = method_params(endpoint)
                .iter()
                .zip(&mode.args)
                .map(|(param, value)| json_arg(param, value))
                .collect();
            let mut options: Map<String, Value> = mode
                .builder_overrides
                .iter()
                .filter_map(|(name, value)| {
                    json_builder_value(endpoint, name, value).map(|v| (name.clone(), v))
                })
                .collect();
            options.insert("timeout_ms".into(), timeout_ms(&mode).into());
            json!({
                "endpoint": endpoint.name,
                "mode": mode.name,
                "min_tier": mode.min_tier,
                "rationale": mode.rationale,
                "args": args,
                "options": options,
            })
            .to_string()
        })
        .collect();
    format!(
        "{{\"@generated\": \"{GENERATED}\", \"cells\": [\n{}\n]}}\n",
        rows.join(",\n")
    )
}

/// The cells as C++ `cell(...)` calls, one per line, for `validate.cpp` to
/// include inside the scope that defines `cell` and `client`.
pub(super) fn render_cpp_cells(endpoints: &[GeneratedEndpoint]) -> String {
    let mut out = format!("// @generated {GENERATED}\n");
    for (endpoint, mode) in cells(endpoints) {
        let mut args: Vec<String> = method_params(endpoint)
            .iter()
            .zip(&mode.args)
            .map(|(param, value)| cpp_arg_literal(param, value))
            .collect();
        let setters: String = mode
            .builder_overrides
            .iter()
            .filter_map(|(name, value)| cpp_builder_setter(endpoint, name, value))
            .collect();
        args.push(format!(
            "thetadatadx::EndpointRequestOptions{{}}{setters}.with_timeout_ms({})",
            timeout_ms(&mode)
        ));
        writeln!(
            out,
            "cell({:?}, {:?}, {:?}, {:?}, [&] {{ return client.{}({}); }});",
            endpoint.name,
            mode.name,
            mode.min_tier,
            mode.rationale,
            endpoint.name,
            args.join(", "),
        )
        .unwrap();
    }
    out
}
