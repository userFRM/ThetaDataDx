#!/usr/bin/env bash
# regen_byte_identical.sh — verify that the build-time generators produce
# byte-identical output across two runs of the same tree.
#
# The generator pipeline lives under `thetadatadx-rs/build_support/*`
# and feeds two sink sets:
#
#   1. `target/<profile>/build/thetadatadx-*/out/*_generated.rs`
#      (consumed by the crate's own source via `include!`).
#   2. Checked-in SDK + tools surfaces (the per-binding `*_generated*`
#      files, the per-language tick/fpss/streaming wrapper files, and the
#      MCP utilities) rewritten by `cargo run --bin generate_sdk_surfaces
#      --features config-file`.
#
# The test captures a SHA-256 snapshot of both sinks, force-reruns the
# build script (by touching build.rs) AND the sdk_surfaces binary, and
# diffs the snapshots. Any non-empty diff means the generators now
# depend on something unstable (HashMap iteration order, unsorted
# input, environment, etc.) — a drift bug that will bite every PR.
#
# HOW TO RUN:
#   bash thetadatadx-rs/tests/regen_byte_identical.sh
#
# Exit code 0 = byte-identical. Non-zero = drift detected; the diff is
# printed on stderr with file paths + before/after hashes.
#
# Run from the REPO ROOT — the script detects this itself and aborts if
# Cargo.toml is not on the caller's PWD.

set -euo pipefail

if [ ! -f "Cargo.toml" ] || ! grep -q 'workspace' Cargo.toml 2>/dev/null; then
    echo "error: run from the repo root (Cargo.toml with [workspace] must exist)" >&2
    exit 2
fi

TMPDIR="$(mktemp -d)"
trap 'rm -rf "$TMPDIR"' EXIT

BEFORE="$TMPDIR/before.sha256"
AFTER="$TMPDIR/after.sha256"

capture() {
    local out="$1"
    : > "$out"
    # OUT_DIR artifacts (from build.rs). Cargo creates one output directory
    # per fingerprint — the hash dir varies across rebuilds, so we strip
    # it and dedupe by basename + content.
    find target -path "*/build/thetadatadx-*/out/*" -type f \
        \( -name "*_generated.rs" -o -name "beta_endpoints.rs" \) 2>/dev/null | \
      while read -r f; do
        printf '%s  out/%s\n' "$(sha256sum "$f" | awk '{print $1}')" "$(basename "$f")"
      done | sort -u >> "$out"

    # Checked-in SDK + tools surfaces, discovered by the header marker every
    # generated file carries.
    #
    # The filter is by file type, not by file name. It used to be a list of
    # names, applied BEFORE the header scan, so a generated file whose name
    # was not on the list was never examined — and fourteen were not,
    # including the FFI event structs and converters, the FFI and binding
    # config accessors, and the Arrow frame projections. The list's own
    # comment claimed it kept the matcher robust against the generator adding
    # a file, which is precisely what it prevented.
    find thetadatadx-rs thetadatadx-ffi thetadatadx-py thetadatadx-ts thetadatadx-cpp tools -type f \
        \( -name "*.rs" -o -name "*.inc" -o -name "*.h" -o -name "*.hpp" \
           -o -name "*.pyi" -o -name "*.ts" -o -name "*.js" \) \
        -not -path "*/target/*" -not -path "*/node_modules/*" 2>/dev/null | \
      while read -r f; do
        if [ -f "$f" ] && head -3 "$f" | grep -qiE "@generated|DO NOT EDIT|Code generated|generated by build|generated by generate_sdk"; then
            sha256sum "$f"
        fi
      done | sort >> "$out"
}

echo "==> Baseline: force-regen and snapshot"
touch thetadatadx-rs/build.rs
cargo build -p thetadatadx-rs --quiet
cargo run -p thetadatadx-rs --bin generate_sdk_surfaces --features config-file --quiet >/dev/null
capture "$BEFORE"
before_lines=$(wc -l < "$BEFORE")
echo "    captured $before_lines file hashes"

# A capture that suddenly sees far fewer files is a narrowed matcher, not a
# clean tree, and the comparison below would call that success. The floor is
# well under the current count and exists to catch a collapse, not to pin a
# number that will drift as generators are added.
MIN_CAPTURED=40
if [ "$before_lines" -lt "$MIN_CAPTURED" ]; then
    echo "!!! captured only $before_lines generated files, expected at least $MIN_CAPTURED." >&2
    echo "    The discovery filter has narrowed; comparing a subset is not a byte-identical check." >&2
    exit 1
fi

echo "==> Regenerate and re-snapshot"
touch thetadatadx-rs/build.rs
cargo build -p thetadatadx-rs --quiet
cargo run -p thetadatadx-rs --bin generate_sdk_surfaces --features config-file --quiet >/dev/null
capture "$AFTER"

if diff -u "$BEFORE" "$AFTER"; then
    echo "OK: generators are byte-identical across $before_lines files"
    exit 0
else
    echo "FAIL: generator output drifted between two runs" >&2
    echo "      the above diff shows changed SHA256 hashes." >&2
    exit 1
fi
